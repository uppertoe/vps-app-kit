type options struct {
	base     string // git ref for the migration check; "" skips it
	upstream bool   // re-download vendored files
}

// lintAll runs every check on an app repository. Findings fail the run;
// warnings are reported and do not.
func lintAll(root string, opt options) (findings, warnings []finding, err error) {
	m, err := manifest.Load(filepath.Join(root, "app.yaml"))
	if err != nil {
		return []finding{{"app.yaml", "manifest", err.Error()}}, nil, nil
	}
	code, err := lint(root)
	if err != nil {
		return nil, nil, err
	}
	findings = append(findings, code...)
	for _, check := range []func(string, *manifest.Manifest) []finding{
		checkCompose, checkEnvExample, checkDocs, checkDockerfile, checkWorkflows, checkGenerated,
	} {
		findings = append(findings, check(root, m)...)
	}
	findings = append(findings, checkVendor(root, opt.upstream)...)
	if opt.base != "" {
		findings = append(findings, checkMigrations(root, opt.base)...)
	}
	findings = append(findings, checkPrivacy(root, m)...)
	if m.HealthUnattested(root) {
		warnings = append(warnings, finding{"app.yaml", "health",
			"this app holds health information and " + m.HealthAttestation + " does not exist: it is a prototype and must not hold real patient data (see compliance/README.md)"})
	}
	return findings, warnings, nil
}

// --- compose: the CIS Docker section 5 block ------------------------------

func checkCompose(root string, m *manifest.Manifest) []finding {
	rel := filepath.Join("deploy", "apps", m.Name, "docker-compose.yml")
	b, err := os.ReadFile(filepath.Join(root, rel))
	if err != nil {
		return []finding{{rel, "compose", "the deploy bundle's compose file is missing"}}
	}
	var doc struct {
		Services map[string]map[string]any `yaml:"services"`
	}
	if err := yaml.Unmarshal(b, &doc); err != nil {
		return []finding{{rel, "compose", err.Error()}}
	}
	var out []finding
	bad := func(msg string) { out = append(out, finding{rel, "compose", msg}) }
	if _, ok := doc.Services[m.Name]; !ok {
		bad("the web service must be named " + m.Name + ", after the app")
	}
	for name, s := range doc.Services {
		where := "service " + name + ": "
		user, _ := s["user"].(string)
		if u, _, _ := strings.Cut(user, ":"); u == "" || u == "0" || u == "root" {
			bad(where + "user must be a non-root uid, such as 65532:65532")
		}
		if !listHas(s["cap_drop"], "ALL") {
			bad(where + "cap_drop must include ALL")
		}
		if !listHas(s["security_opt"], "no-new-privileges:true") {
			bad(where + "security_opt must include no-new-privileges:true")
		}
		if ro, _ := s["read_only"].(bool); !ro {
			bad(where + "read_only must be true")
		}
		for _, k := range []string{"mem_limit", "pids_limit", "healthcheck"} {
			if _, ok := s[k]; !ok {
				bad(where + k + " is required")
			}
		}
		for _, k := range []string{"ports", "network_mode", "privileged", "pid", "ipc", "devices"} {
			if _, ok := s[k]; ok {
				bad(where + k + " is not allowed: Caddy is the only way in")
			}
		}
		if _, ok := s["networks"]; ok && name == m.Name {
			bad(where + "networks is not allowed on the web service: the proxy network is generated by the server repo")
		}
		if env, ok := s["environment"]; ok && strings.Contains(fmt.Sprint(env), "DEV_AUTH") {
			bad(where + "DEV_AUTH must never be set")
		}
	}
	return out
}

func listHas(v any, want string) bool {
	xs, _ := v.([]any)
	for _, x := range xs {
		if s, _ := x.(string); s == want {
			return true
		}
	}
	return false
}

// --- .env.example ----------------------------------------------------------

var secretKeyRe = regexp.MustCompile(`(?i)(PASS|PASSWORD|SECRET|TOKEN|KEY)$`)

func checkEnvExample(root string, m *manifest.Manifest) []finding {
	rel := filepath.Join("deploy", "apps", m.Name, ".env.example")
	b, err := os.ReadFile(filepath.Join(root, rel))
	if err != nil {
		return []finding{{rel, "env", ".env.example is missing"}}
	}
	var out []finding
	for i, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "#"))
		k, v, ok := strings.Cut(line, "=")
		if !ok || strings.ContainsAny(k, " \t") {
			continue
		}
		pos := fmt.Sprintf("%s:%d", rel, i+1)
		if k == "DEV_AUTH" {
			out = append(out, finding{pos, "env", "DEV_AUTH must never appear in a deployment"})
		}
		if secretKeyRe.MatchString(k) && v != "" && v != "CHANGE_ME" {
			out = append(out, finding{pos, "secret", k + " must be empty or CHANGE_ME in the example; the real value lives only on the server"})
		}
	}
	return out
}

// --- design-docs: the docs site's contract ---------------------------------

var (
	docSecretRe = regexp.MustCompile(`[A-Z0-9_]*_(TOKEN|SECRET|PASSWORD|PASS|KEY)\b`)
	docGUIDRe   = regexp.MustCompile(`(?i)\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b`)
	mdLinkRe    = regexp.MustCompile(`\]\(([^)#\s]+)(#[^)]*)?\)`)
)

func checkDocs(root string, _ *manifest.Manifest) []finding {
	dir := filepath.Join(root, "design-docs")
	var out []finding
	bad := func(rel, msg string) { out = append(out, finding{rel, "docs", msg}) }
	if _, err := os.Stat(filepath.Join(dir, "_index.md")); err != nil {
		return []finding{{"design-docs/_index.md", "docs", "the project's front page is missing"}}
	}
	_ = filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(root, p)
		b, _ := os.ReadFile(p)
		s := string(b)
		if docSecretRe.MatchString(s) {
			bad(rel, "names a secret setting ("+docSecretRe.FindString(s)+"); the docs site refuses it")
		}
		if docGUIDRe.MatchString(s) {
			bad(rel, "contains an identifier shaped like a GUID; the docs site refuses it")
		}
		if !strings.HasSuffix(p, ".md") {
			return nil
		}
		front, body, ok := frontMatter(s)
		if !ok {
			bad(rel, "needs front matter")
			return nil
		}
		need := []string{"title"}
		if d.Name() == "_index.md" {
			need = []string{"title", "summary", "status", "contact", "decided-by"}
			switch strings.Trim(front["status"], `"'`) {
			case "in development", "live", "retired":
			default:
				bad(rel, `status must be "in development", "live" or "retired"`)
			}
			if strings.TrimSpace(body) == "" {
				bad(rel, "the front page needs some body text")
			}
		}
		for _, k := range need {
			if strings.TrimSpace(front[k]) == "" {
				bad(rel, "needs "+k+" in its front matter")
			}
		}
		for _, l := range mdLinkRe.FindAllStringSubmatch(body, -1) {
			target := l[1]
			if strings.Contains(target, "://") || strings.HasPrefix(target, "mailto:") {
				continue
			}
			if _, err := os.Stat(filepath.Join(filepath.Dir(p), target)); err != nil {
				bad(rel, "links to "+target+", which is not a page in design-docs")
			}
		}
		return nil
	})
	return out
}

func frontMatter(s string) (map[string]string, string, bool) {
	if !strings.HasPrefix(s, "---\n") {
		return nil, s, false
	}
	end := strings.Index(s[4:], "\n---")
	if end < 0 {
		return nil, s, false
	}
	m := map[string]string{}
	var raw map[string]any
	if err := yaml.Unmarshal([]byte(s[4:4+end]), &raw); err != nil {
		return nil, s, false
	}
	for k, v := range raw {
		m[k] = fmt.Sprint(v)
	}
	return m, s[4+end+4:], true
}

// --- vendored JavaScript ---------------------------------------------------

type vendorFile struct {
	Path    string `json:"path"`
	Package string `json:"package"`
	Version string `json:"version"`
	File    string `json:"file"`
	URL     string `json:"url"`
	SHA256  string `json:"sha256"`
}

var exactVersionRe = regexp.MustCompile(`^\d+\.\d+\.\d+$`)

func checkVendor(root string, upstream bool) []finding {
	rel := filepath.Join("internal", "web", "static", "js", "VENDOR.json")
	b, err := os.ReadFile(filepath.Join(root, rel))
	if err != nil {
		return []finding{{rel, "vendor", "VENDOR.json is missing"}}
	}
	var doc struct {
		Files []vendorFile `json:"files"`
	}
	if err := json.Unmarshal(b, &doc); err != nil {
		return []finding{{rel, "vendor", err.Error()}}
	}
	var out []finding
	bad := func(msg string) { out = append(out, finding{rel, "vendor", msg}) }
	listed := map[string]bool{}
	for _, f := range doc.Files {
		listed[filepath.Clean(f.Path)] = true
		want := "https://cdn.jsdelivr.net/npm/" + f.Package + "@" + f.Version + f.File
		if !exactVersionRe.MatchString(f.Version) || f.URL != want {
			bad(f.Path + ": the url must be " + want + ", with an exact version")
			continue
		}
		data, err := os.ReadFile(filepath.Join(root, "internal", "web", "static", "js", f.Path))
		if err != nil {
			bad(f.Path + ": listed but missing")
			continue
		}
		if sum(data) != f.SHA256 {
			bad(f.Path + ": the file does not match its recorded sha256")
		}
		if upstream {
			if msg := checkUpstream(f, data); msg != "" {
				bad(f.Path + ": " + msg)
			}
		}
	}
	vdir := filepath.Join(root, "internal", "web", "static", "js", "vendor")
	entries, _ := os.ReadDir(vdir)
	for _, e := range entries {
		if !listed[filepath.Join("vendor", e.Name())] {
			bad("vendor/" + e.Name() + " is not listed in VENDOR.json")
		}
	}
	return out
}

func sum(b []byte) string {
	h := sha256.Sum256(b)
	return base64.StdEncoding.EncodeToString(h[:])
}

func checkUpstream(f vendorFile, local []byte) string {
	c := &http.Client{Timeout: 30 * time.Second}
	resp, err := c.Get(f.URL)
	if err != nil {
		return "could not download from the registry: " + err.Error()
	}
	defer resp.Body.Close()
	remote, err := io.ReadAll(io.LimitReader(resp.Body, 10<<20))
	if err != nil || resp.StatusCode != 200 {
		return fmt.Sprintf("could not download from the registry (status %d)", resp.StatusCode)
	}
	if !bytes.Equal(remote, local) {
		return "the file differs from the registry's copy of " + f.Package + "@" + f.Version
	}
	api := "https://data.jsdelivr.com/v1/packages/npm/" + f.Package + "@" + f.Version + "?structure=flat"
	resp2, err := c.Get(api)
	if err != nil {
		return "could not read the registry's hashes: " + err.Error()
	}
	defer resp2.Body.Close()
	var listing struct {
		Files []struct{ Name, Hash string } `json:"files"`
	}
	if err := json.NewDecoder(resp2.Body).Decode(&listing); err != nil {
		return "could not read the registry's hashes"
	}
	for _, x := range listing.Files {
		if x.Name == f.File {
			if x.Hash != f.SHA256 {
				return "the recorded sha256 differs from the registry's published hash"
			}
			return ""
		}
	}
	return "the registry does not list " + f.File
}

// --- migrations: merged files never change ----------------------------------

func checkMigrations(root, base string) []finding {
	dir := "internal/store/migrations"
	cmd := exec.Command("git", "ls-tree", "--name-only", base+":"+dir)
	cmd.Dir = root
	listing, err := cmd.Output()
	if err != nil {
		return nil // the base has no migrations yet
	}
	var out []finding
	for _, name := range strings.Fields(string(listing)) {
		rel := dir + "/" + name
		show := exec.Command("git", "show", base+":"+rel)
		show.Dir = root
		old, err := show.Output()
		if err != nil {
			continue
		}
		cur, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			out = append(out, finding{rel, "migration", "a merged migration has been deleted; add a new numbered file instead"})
			continue
		}
		if !bytes.Equal(old, cur) {
			out = append(out, finding{rel, "migration", "a merged migration has been edited; add a new numbered file instead"})
		}
	}
	return out
}

// --- generated files ------------------------------------------------------

func checkGenerated(root string, m *manifest.Manifest) []finding {
	var out []finding
	for _, g := range []struct{ flag, rel string }{
		{"-caddy", filepath.Join("deploy", "apps", m.Name, m.Name+".caddy")},
		{"-connections", filepath.Join("design-docs", "connections.md")},
	} {
		cmd := exec.Command("go", "run", "./cmd/server", g.flag)
		cmd.Dir = root
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		fresh, err := cmd.Output()
		if err != nil {
			out = append(out, finding{g.rel, "generated", "could not generate: " + strings.TrimSpace(stderr.String())})
			continue
		}
		cur, _ := os.ReadFile(filepath.Join(root, g.rel))
		if !bytes.Equal(fresh, cur) {
			out = append(out, finding{g.rel, "generated", "differs from a fresh generation; run make generate and commit the result"})
		}
	}
	return out
}

// --- Dockerfile -------------------------------------------------------------

var (
	fromRe   = regexp.MustCompile(`(?im)^\s*FROM\s+(\S+)`)
	devTagRe = regexp.MustCompile(`-tags[ =]+["']?[^"'\s]*\bdev\b`)
	digestRe = regexp.MustCompile(`@sha256:[0-9a-f]{64}$`)
)

func checkDockerfile(root string, _ *manifest.Manifest) []finding {
	b, err := os.ReadFile(filepath.Join(root, "Dockerfile"))
	if err != nil {
		return []finding{{"Dockerfile", "dockerfile", "the Dockerfile is missing"}}
	}
	var out []finding
	// Comments may mention the dev tag (to warn against it); instructions may not.
	var lines []string
	for _, l := range strings.Split(string(b), "\n") {
		if !strings.HasPrefix(strings.TrimSpace(l), "#") {
			lines = append(lines, l)
		}
	}
	s := strings.Join(lines, "\n")
	if devTagRe.MatchString(s) {
		out = append(out, finding{"Dockerfile", "dockerfile", "the image must never be built with the dev tag, which contains the sign-in stand-in"})
	}
	for _, mm := range fromRe.FindAllStringSubmatch(s, -1) {
		img := mm[1]
		if strings.EqualFold(img, "scratch") || !strings.Contains(img, ":") && !strings.Contains(img, "@") && !strings.Contains(img, "/") {
			continue // scratch or an earlier stage's name
		}
		if !digestRe.MatchString(img) {
			out = append(out, finding{"Dockerfile", "dockerfile", img + " must be pinned by digest (@sha256:...)"})
		}
	}
	return out
}

// --- workflows --------------------------------------------------------------

var (
	usesRe   = regexp.MustCompile(`(?m)^\s*-?\s*uses:\s*([^\s#]+)`)
	shaPinRe = regexp.MustCompile(`@[0-9a-f]{40}$`)
	permsRe  = regexp.MustCompile(`(?m)^permissions:`)
	writeAll = regexp.MustCompile(`(?m)^\s*permissions:\s*write-all`)
	targetRe = regexp.MustCompile(`(?m)^\s*(pull_request_target|workflow_run)\s*:`)
)

func checkWorkflows(root string, _ *manifest.Manifest) []finding {
	var out []finding
	files, _ := filepath.Glob(filepath.Join(root, ".github", "workflows", "*.y*ml"))
	for _, p := range files {
		rel, _ := filepath.Rel(root, p)
		b, _ := os.ReadFile(p)
		s := string(b)
		bad := func(msg string) { out = append(out, finding{rel, "workflow", msg}) }
		if targetRe.MatchString(s) {
			bad("pull_request_target and workflow_run can run untrusted code with secrets; use pull_request")
		}
		if writeAll.MatchString(s) {
			bad("permissions: write-all is not allowed; grant each job only what it needs")
		}
		if !permsRe.MatchString(s) {
			bad("declare a top-level permissions block, such as permissions: {}")
		}
		for _, mm := range usesRe.FindAllStringSubmatch(s, -1) {
			u := mm[1]
			if strings.HasPrefix(u, "./") || strings.HasPrefix(u, "docker://") {
				continue
			}
			if !shaPinRe.MatchString(u) {
				bad(u + " must be pinned to a full commit SHA")
			}
		}
	}
	return out
}

// --- privacy: an app holding personal information says what it does --------

func checkPrivacy(root string, m *manifest.Manifest) []finding {
	if m.DataClass == manifest.DataNone {
		return nil
	}
	var out []finding
	if _, err := os.Stat(filepath.Join(root, "design-docs", "privacy.md")); err != nil {
		out = append(out, finding{"design-docs/privacy.md", "privacy",
			"an app whose data_class is " + string(m.DataClass) + " needs a privacy page in its design docs: what it holds, who sees it, where it is kept and for how long"})
	}
	cmd := exec.Command("go", "run", "./cmd/server", "-routes")
	cmd.Dir = root
	routes, err := cmd.Output()
	if err != nil {
		return append(out, finding{"internal/web/server.go", "privacy", "could not list the routes"})
	}
	if !regexp.MustCompile(`(?m)^GET\s+/privacy\s+public\b`).Match(routes) {
		out = append(out, finding{"internal/web/server.go", "privacy",
			"an app whose data_class is " + string(m.DataClass) + " needs a public GET /privacy page for the people whose information it holds"})
	}
	return out
}
